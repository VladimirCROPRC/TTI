CREATE TABLE IF NOT EXISTS points (
 id TEXT PRIMARY KEY, category TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '',
 deleted INTEGER NOT NULL DEFAULT 0, version INTEGER NOT NULL DEFAULT 0,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 latitude REAL, longitude REAL, name TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS photos (
 id TEXT PRIMARY KEY, point_id TEXT NOT NULL REFERENCES points(id),
 object_key TEXT NOT NULL UNIQUE, caption TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS observations (
 id TEXT PRIMARY KEY, point_id TEXT NOT NULL REFERENCES points(id),
 text TEXT NOT NULL, created_at TEXT NOT NULL, legacy INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS observations_point_date ON observations(point_id,created_at);
CREATE TABLE IF NOT EXISTS deleted_photos (
 point_id TEXT NOT NULL REFERENCES points(id), src TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(point_id,src)
);
CREATE TABLE IF NOT EXISTS cables (
 id TEXT PRIMARY KEY, status TEXT NOT NULL DEFAULT 'Neprogramate',
 scheduled_week TEXT, patrolled_week TEXT, version INTEGER NOT NULL DEFAULT 0,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS drawn_cables (
 id TEXT PRIMARY KEY REFERENCES cables(id),
 name TEXT NOT NULL, coordinates TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS deleted_cables (
 cable_id TEXT PRIMARY KEY REFERENCES cables(id),
 deleted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cable_sections (
 sequence INTEGER PRIMARY KEY AUTOINCREMENT, id TEXT NOT NULL UNIQUE,
 cable_id TEXT NOT NULL REFERENCES cables(id), status TEXT NOT NULL,
 start_pos REAL NOT NULL, end_pos REAL NOT NULL, week TEXT NOT NULL,
 created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS deleted_cable_sections (
 section_id TEXT PRIMARY KEY REFERENCES cable_sections(id),
 deleted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS kmz_imports(id TEXT PRIMARY KEY,label TEXT NOT NULL,active INTEGER NOT NULL DEFAULT 1,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS imported_features(id TEXT PRIMARY KEY,import_id TEXT NOT NULL REFERENCES kmz_imports(id),feature_type TEXT NOT NULL,original_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS operation_history(id TEXT PRIMARY KEY,kind TEXT NOT NULL,title TEXT NOT NULL,payload TEXT NOT NULL,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,undone_at TEXT);
